#!/usr/bin/env python3
"""Summarise the scores of an rst recipe experiment as Markdown (RESULTS.md).

Reads what the scoring stages of egs2/TEMPLATE/rst1/rst.sh write under <expdir>:
    score_<test_set>/scores.json                          (stage 10)
    inference_<test_set>/scoring/versa_eval/avg_result.txt (stage 11)
    inference_<test_set>/scoring/versa_ref/avg_result.txt  (stage 11, optional)
and prints one table per kind of score, one row per test set.
"""

import argparse
import json
import re
import subprocess
import sys
from datetime import datetime
from pathlib import Path

# aggregate_eval.py writes the raw edit counts behind each WER/CER next to the
# rates themselves; only the rates belong in a summary.
EDIT_COUNT = re.compile(r"_(wer|cer)_(insert|delete|replace|equal)$")


def read_avg_result(path):
    """Read an aggregate_eval.py avg_result.txt ("key: value" or "key value")."""
    scores = {}
    for line in Path(path).read_text().splitlines():
        if not line.strip():
            continue
        key, value = re.split(r":?\s+", line.strip(), maxsplit=1)
        if EDIT_COUNT.search(key):
            continue
        try:
            scores[key] = float(value)
        except ValueError:
            scores[key] = value
    return scores


def collect(expdir, pattern):
    """Map test set -> scores for every file matching <expdir>/<pattern>."""
    rows = {}
    prefix, suffix = pattern.split("*")
    for path in sorted(expdir.glob(pattern)):
        relative = path.relative_to(expdir).as_posix()
        test_set = relative[len(prefix) : len(relative) - len(suffix)]
        if path.suffix == ".json":
            rows[test_set] = json.loads(path.read_text())
        else:
            rows[test_set] = read_avg_result(path)
    return rows


def format_value(value):
    if isinstance(value, float):
        return f"{value:.4f}"
    return str(value)


def table(title, rows):
    columns = []
    for scores in rows.values():
        columns += [key for key in scores if key not in columns]
    lines = [f"### {title}", "", "|dataset|" + "|".join(columns) + "|"]
    lines.append("|---|" + "---|" * len(columns))
    for test_set, scores in rows.items():
        cells = [format_value(scores[key]) if key in scores else "" for key in columns]
        lines.append(f"|{test_set}|" + "|".join(cells) + "|")
    return lines + [""]


def environment():
    lines = [f"- date: `{datetime.now().strftime('%a %b %d %H:%M:%S %Y')}`"]
    lines.append(f"- python version: `{sys.version.replace(chr(10), ' ')}`")
    try:
        import espnet2

        lines.append(f"- espnet2 version: `espnet2 {espnet2.__version__}`")
    except ImportError:
        pass
    try:
        import torch

        lines.append(f"- pytorch version: `pytorch {torch.__version__}`")
    except ImportError:
        pass
    try:
        git = ["git", "log", "-1", "--format=%H%n%cd"]
        commit, date = subprocess.check_output(git, text=True).splitlines()
        lines += [f"- Git hash: `{commit}`", f"  - Commit date: `{date}`"]
    except (OSError, subprocess.CalledProcessError, ValueError):
        pass
    return lines


def main(cmd=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("expdir", type=Path, help="feature-predictor experiment")
    args = parser.parse_args(cmd)

    sections = [
        ("Scores (stage 10, local/score.py)", "score_*/scores.json"),
        ("VERSA (stage 11)", "inference_*/scoring/versa_eval/avg_result.txt"),
        (
            "VERSA against the clean reference (stage 11, --ref_wav_scp)",
            "inference_*/scoring/versa_ref/avg_result.txt",
        ),
    ]
    lines = [f"<!-- Generated by {Path(__file__).name} -->", "# RESULTS"]
    lines += ["## Environments"] + environment() + ["", f"## {args.expdir.name}", ""]
    for title, pattern in sections:
        rows = collect(args.expdir, pattern)
        if rows:
            lines += table(title, rows)
    print("\n".join(lines))


if __name__ == "__main__":
    main()
