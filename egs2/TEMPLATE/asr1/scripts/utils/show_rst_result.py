#!/usr/bin/env python3
"""Collect the stage-11 VERSA averages of a restoration experiment into RESULTS.md.

Reads ``<expdir>/inference_<set>/scoring/versa_eval/avg_result.txt`` (the
reference-free pass; always present after stage 11) and, when stage 11 was
given a clean reference, ``.../scoring/versa_ref/avg_result.txt``, for every
evaluation set, and writes one table per set. Metrics are listed as VERSA
names them; the per-utterance files next to them hold the full detail.

    python3 scripts/utils/show_rst_result.py --expdir exp/rst_w2v_bert2 \\
        --test_sets "test-clean test-other" > exp/rst_w2v_bert2/RESULTS.md
"""

import argparse
import datetime
from pathlib import Path


def read_averages(path: Path):
    """Parse aggregate_eval.py's avg_result.txt into an ordered dict."""
    values = {}
    with open(path, encoding="utf-8") as stream:
        for line in stream:
            line = line.strip()
            if not line:
                continue
            # "key: value" for averages, "tag_wer value" for the error rates
            key, _, value = line.replace(": ", " ", 1).partition(" ")
            try:
                values[key] = float(value)
            except ValueError:
                continue
    return values


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("--expdir", required=True)
    parser.add_argument("--test_sets", required=True, help="space-separated")
    args = parser.parse_args()
    expdir = Path(args.expdir)

    lines = ["<!-- Generated by scripts/utils/show_rst_result.py -->"]
    lines.append("# RESULTS")
    lines.append(f"## Environment\n- date: `{datetime.datetime.now():%c}`")
    lines.append(f"- experiment: `{expdir}`\n")
    found = False
    for test_set in args.test_sets.split():
        scoring = expdir / f"inference_{test_set}" / "scoring"
        for pass_name, title in (
            ("versa_eval", "reference-free (input as --gt)"),
            ("versa_ref", "reference-based (clean reference as --gt)"),
        ):
            avg = scoring / pass_name / "avg_result.txt"
            if not avg.is_file():
                continue
            found = True
            values = read_averages(avg)
            lines.append(f"## {test_set}: {title}\n")
            lines.append("| metric | value |\n|---|---|")
            for key, value in values.items():
                lines.append(f"| {key} | {value:.4f} |")
            lines.append("")
    if not found:
        lines.append("No VERSA averages found: run stage 11 first.")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
